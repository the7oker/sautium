"""
Claude Code subprocess wrapper for AI DJ.

Calls `claude -p` in headless mode with MCP tools (PostgreSQL + HQPlayer).
Returns the raw model answer (including any DJ_BLOCKS marker) — the chat
router parses + hydrates the marker centrally so this wrapper stays
format-agnostic.

Two flavours:
- `call_claude_code` — synchronous, `--output-format json`, returns the
  full answer in one go.
- `call_claude_code_stream` — streaming, `--output-format stream-json
  --include-partial-messages`, yields text deltas / tool starts / a
  final done event so the chat router can pipe them into SSE.
"""

import json
import logging
import os
import shutil
import subprocess
import sys
import threading
from pathlib import Path
from typing import Any, Dict, Iterator, Optional

if sys.platform not in ("win32", "darwin"):
    import pwd

from providers.base import StreamDone, StreamEvent, TextDelta, ToolStart

logger = logging.getLogger(__name__)

if sys.platform in ("win32", "darwin"):
    # Desktop mode (Win/Mac): mcp config sits next to this module and is
    # regenerated by the launcher with current ports + credentials.
    MCP_CONFIG_PATH = str(Path(__file__).parent / "mcp-windows.json")
else:
    MCP_CONFIG_PATH = "/app/mcp-docker.json"

DEFAULT_MODEL = "sonnet"
ALLOWED_MODELS = {"sonnet", "haiku"}
# Kept below the ~180s at which the browser/LAN drops the streaming connection,
# so the graceful timeout `done` event reaches the client (a clean "took too
# long" message) instead of the stream dying as a raw "network error".
TIMEOUT_SECONDS = 150
CLAUDE_USER = "claudeuser"  # non-root user (--dangerously-skip-permissions requires non-root)


def _resolve_claude_executable() -> Optional[str]:
    """Path to the native Claude Code binary, bypassing npm's shim.

    The .cmd shim that npm creates on Windows runs through cmd.exe, which
    caps the command line at 8191 chars — far less than our system_prompt
    (~13.5k). Calling the native binary directly uses CreateProcessW with
    the 32k Win32 limit, which fits comfortably. The native binary is
    named `claude.exe` on every platform (the postinstall script copies
    a platform-matched ELF/Mach-O/PE over the placeholder).

    Resolution order: bundled per-user prefix (wizard install) → npm shim
    in PATH redirected to its sibling .exe → raw shim as last resort."""
    bin_rel = (
        Path("node_modules") / "@anthropic-ai" / "claude-code"
        / "bin" / "claude.exe"
    )

    if sys.platform == "win32":
        appdata = os.environ.get("LOCALAPPDATA")
        if appdata:
            bundled = Path(appdata) / "Sautium" / "claude-prefix" / bin_rel
            if bundled.is_file():
                return str(bundled)
    elif sys.platform == "darwin":
        bundled = (
            Path.home() / "Library" / "Application Support"
            / "Sautium" / "claude-prefix" / bin_rel
        )
        if bundled.is_file():
            return str(bundled)

    shim = shutil.which("claude")
    if shim:
        shim_dir = Path(shim).parent
        # npm layout 1 (local prefix): shim in node_modules/.bin/, exe in
        # node_modules/<scope>/<pkg>/bin/ — two dirs up from shim.
        # npm layout 2 (global, Windows): shim in <prefix>/, exe in
        # <prefix>/node_modules/<scope>/<pkg>/bin/ — one dir up.
        for cand in (
            shim_dir.parent / "@anthropic-ai" / "claude-code" / "bin" / "claude.exe",
            shim_dir / "node_modules" / "@anthropic-ai" / "claude-code" / "bin" / "claude.exe",
        ):
            if cand.is_file():
                return str(cand)
        return shim
    return None


def call_claude_code(
    message: str,
    system_prompt: str,
    session_id: Optional[str] = None,
    resume: bool = False,
    model: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Call Claude Code CLI in headless mode.

    Args:
        message: User message to send
        system_prompt: System prompt for AI DJ context
        session_id: Previous Claude Code session ID for continuity
        resume: Whether to resume a previous session
        model: Model to use (sonnet or haiku). Defaults to DEFAULT_MODEL.

    Returns:
        dict with keys: answer, tracks, claude_session_id, model
    """
    use_model = model if model in ALLOWED_MODELS else DEFAULT_MODEL

    claude_exe = _resolve_claude_executable()
    if claude_exe is None:
        logger.error("Claude Code CLI not found")
        return {
            "answer": "Claude Code CLI is not installed. Open Settings to run AI agent setup.",
            "claude_session_id": None,
            "model": use_model,
        }

    cmd = [
        claude_exe,
        "-p", message,
        "--output-format", "json",
        "--mcp-config", MCP_CONFIG_PATH,
        "--model", use_model,
        "--system-prompt", system_prompt,
        "--dangerously-skip-permissions",
    ]

    if resume and session_id:
        cmd.extend(["--resume", session_id])

    logger.info(f"Claude Code call: message={message[:80]!r}, resume={resume}, session={session_id}")

    try:
        env = os.environ.copy()
        # Force the CLI onto OAuth credentials (Claude subscription) rather
        # than the pay-as-you-go API key — see same comment in _spawn_claude.
        env.pop("ANTHROPIC_API_KEY", None)
        kwargs = {
            "capture_output": True,
            "text": True,
            "encoding": "utf-8",
            "errors": "replace",
            "timeout": TIMEOUT_SECONDS,
            "env": env,
        }

        if sys.platform == "win32":
            kwargs["creationflags"] = subprocess.CREATE_NO_WINDOW
        elif sys.platform != "darwin":
            # Linux/Docker: run as non-root user
            pw = pwd.getpwnam(CLAUDE_USER)

            def demote():
                os.setgid(pw.pw_gid)
                os.setuid(pw.pw_uid)

            kwargs["preexec_fn"] = demote
            env["HOME"] = pw.pw_dir

        result = subprocess.run(cmd, **kwargs)

        if result.returncode != 0:
            stderr = result.stderr.strip()
            logger.error(f"Claude Code failed (rc={result.returncode}): {stderr}")
            return {
                "answer": f"Claude Code error: {stderr or 'unknown error'}",
                "claude_session_id": None,
                "model": use_model,
            }

        # Parse JSON output
        try:
            output = json.loads(result.stdout)
        except json.JSONDecodeError as e:
            logger.error(f"Failed to parse Claude Code JSON: {e}\nstdout: {result.stdout[:500]}")
            return {
                "answer": result.stdout.strip() or "Failed to parse Claude Code response",
                "claude_session_id": None,
                "model": use_model,
            }

        raw_answer = output.get("result", "")
        claude_sid = output.get("session_id")

        if output.get("is_error") and output.get("api_error_status") == 401:
            raw_answer = (
                "Claude Code OAuth token expired. "
                "Run `claude /login` on the host to refresh — "
                "the container will pick up the new token automatically "
                "(no restart needed)."
            )

        logger.info(
            f"Claude Code response: {len(raw_answer)} chars, session={claude_sid}"
        )

        return {
            "answer": raw_answer,
            "claude_session_id": claude_sid,
            "model": use_model,
        }

    except subprocess.TimeoutExpired:
        logger.error(f"Claude Code timed out after {TIMEOUT_SECONDS}s")
        return {
            "answer": "Request timed out. Please try a simpler query.",
            "claude_session_id": None,
            "model": use_model,
        }
    except FileNotFoundError:
        logger.error("Claude Code CLI not found. Is it installed?")
        return {
            "answer": "Claude Code CLI is not installed in this environment.",
            "claude_session_id": None,
            "model": use_model,
        }
    except Exception as e:
        logger.error(f"Unexpected error calling Claude Code: {e}")
        return {
            "answer": f"Error: {e}",
            "claude_session_id": None,
            "model": use_model,
        }


def _spawn_claude(cmd: list[str], stdout=subprocess.PIPE, stderr=subprocess.PIPE):
    """Common subprocess setup — non-root user on Linux/Docker, no
    flashing console window on Windows. Returns the Popen handle."""
    env = os.environ.copy()
    # Force the CLI onto OAuth credentials (Claude subscription) rather
    # than the pay-as-you-go API key. When ANTHROPIC_API_KEY is set in
    # the env, the CLI silently uses it and bills against that account
    # — which on this deployment was exhausted. The Python Anthropic
    # SDK (used by the separate "anthropic_api" provider) keeps its
    # env access via os.environ; only the Claude Code subprocess gets
    # the variable stripped.
    env.pop("ANTHROPIC_API_KEY", None)
    kwargs: dict[str, Any] = {
        "stdout": stdout,
        "stderr": stderr,
        "env": env,
        "text": True,
        "encoding": "utf-8",
        "errors": "replace",
    }

    if sys.platform == "win32":
        kwargs["creationflags"] = subprocess.CREATE_NO_WINDOW
    elif sys.platform != "darwin":
        # Linux/Docker: run as non-root user
        pw = pwd.getpwnam(CLAUDE_USER)

        def demote():
            os.setgid(pw.pw_gid)
            os.setuid(pw.pw_uid)

        kwargs["preexec_fn"] = demote
        env["HOME"] = pw.pw_dir

    return subprocess.Popen(cmd, **kwargs)


def call_claude_code_stream(
    message: str,
    system_prompt: str,
    session_id: Optional[str] = None,
    resume: bool = False,
    model: Optional[str] = None,
) -> Iterator[StreamEvent]:
    """Stream variant of `call_claude_code`. Spawns `claude
    --output-format stream-json --include-partial-messages` and turns
    its NDJSON output into provider stream events.

    The partial-messages flag delivers token-level Anthropic stream
    events (`content_block_delta` / `text_delta`) inside a
    `stream_event` wrapper; we forward those as `TextDelta`s. Tool
    invocations show up as either `content_block_start` (tool_use)
    inside `stream_event`, or as fully-formed `assistant` messages
    when the SDK couldn't stream the tool partial — both paths emit
    a single `ToolStart` per call.
    """
    use_model = model if model in ALLOWED_MODELS else DEFAULT_MODEL

    claude_exe = _resolve_claude_executable()
    if claude_exe is None:
        logger.error("Claude Code CLI not found")
        yield StreamDone(
            model=use_model, provider="claude_code",
            error="Claude Code CLI is not installed. Open Settings to run AI agent setup.",
        )
        return

    cmd = [
        claude_exe,
        "-p", message,
        "--output-format", "stream-json",
        "--include-partial-messages",
        "--verbose",  # required for stream-json
        "--mcp-config", MCP_CONFIG_PATH,
        "--model", use_model,
        "--system-prompt", system_prompt,
        "--dangerously-skip-permissions",
    ]
    if resume and session_id:
        cmd.extend(["--resume", session_id])

    logger.info(
        f"Claude Code stream call: message={message[:80]!r}, resume={resume}, session={session_id}"
    )

    try:
        proc = _spawn_claude(cmd)
    except FileNotFoundError:
        logger.error("Claude Code CLI not found")
        yield StreamDone(
            model=use_model, provider="claude_code",
            error="Claude Code CLI is not installed",
        )
        return
    except Exception as e:
        logger.error(f"Failed to spawn Claude Code: {e}")
        yield StreamDone(
            model=use_model, provider="claude_code", error=str(e),
        )
        return

    claude_sid: Optional[str] = None
    tool_calls_count = 0
    seen_tool_ids: set[str] = set()
    error_msg: Optional[str] = None

    # Watchdog: kill the subprocess after TIMEOUT_SECONDS regardless of
    # whether it's currently producing output. `proc.wait(timeout=...)`
    # only catches a wedged exit; a subprocess that loops over tool
    # calls forever would otherwise sit on `for line in proc.stdout:`
    # indefinitely.
    timed_out = threading.Event()

    def _watchdog():
        if proc.poll() is None:
            timed_out.set()
            logger.warning(
                f"Claude Code wallclock timeout ({TIMEOUT_SECONDS}s); killing subprocess"
            )
            try:
                proc.kill()
            except Exception:
                pass

    watchdog = threading.Timer(TIMEOUT_SECONDS, _watchdog)
    watchdog.daemon = True
    watchdog.start()

    # Drain stderr in a background thread so it doesn't block on a
    # full pipe and so the message is available on failures.
    stderr_chunks: list[str] = []

    def _drain_stderr():
        if proc.stderr is None:
            return
        try:
            for line in proc.stderr:
                stderr_chunks.append(line)
        except Exception:
            pass

    stderr_thread = threading.Thread(target=_drain_stderr, daemon=True)
    stderr_thread.start()

    def _yield_block_event(block: dict) -> Iterator[StreamEvent]:
        """Translate a single content block (text or tool_use) into
        events. Used when we receive whole assistant messages without
        partial deltas, so we don't drop content."""
        nonlocal tool_calls_count
        bt = block.get("type")
        if bt == "text":
            text = block.get("text", "")
            if text:
                yield TextDelta(text=text)
        elif bt == "tool_use":
            tu_id = block.get("id") or ""
            if tu_id and tu_id in seen_tool_ids:
                return
            if tu_id:
                seen_tool_ids.add(tu_id)
            tool_calls_count += 1
            yield ToolStart(name=block.get("name", "tool"))

    try:
        assert proc.stdout is not None
        for line in proc.stdout:
            line = line.strip()
            if not line:
                continue
            try:
                evt = json.loads(line)
            except json.JSONDecodeError:
                logger.debug(f"Claude stream: skipping non-JSON line: {line[:120]}")
                continue

            t = evt.get("type")

            if t == "system":
                if evt.get("session_id"):
                    claude_sid = evt["session_id"]

            elif t == "stream_event":
                inner = evt.get("event") or {}
                inner_type = inner.get("type")
                if inner_type == "content_block_delta":
                    delta = inner.get("delta") or {}
                    if delta.get("type") == "text_delta":
                        text = delta.get("text", "")
                        if text:
                            yield TextDelta(text=text)
                elif inner_type == "content_block_start":
                    cb = inner.get("content_block") or {}
                    if cb.get("type") == "tool_use":
                        tu_id = cb.get("id") or ""
                        if tu_id and tu_id not in seen_tool_ids:
                            seen_tool_ids.add(tu_id)
                            tool_calls_count += 1
                            yield ToolStart(name=cb.get("name", "tool"))

            elif t == "assistant":
                # Whole assistant message — only mine it for content
                # we haven't already streamed via stream_event. Tool
                # blocks get deduped by `seen_tool_ids`; text blocks
                # are tricky because partial deltas already covered
                # them. Skip text here to avoid double-rendering.
                msg = evt.get("message") or {}
                for block in msg.get("content", []) or []:
                    if block.get("type") == "tool_use":
                        yield from _yield_block_event(block)

            elif t == "result":
                if evt.get("session_id"):
                    claude_sid = evt["session_id"]
                if evt.get("is_error"):
                    # Surface the real error message instead of the
                    # generic "Claude Code error". `errors` is a list
                    # set by the CLI on early-exit failures (e.g.
                    # `--resume <unknown-id>`); `result` carries the
                    # human-readable text on normal API errors.
                    errs = evt.get("errors") or []
                    api_status = evt.get("api_error_status")
                    if api_status == 401:
                        # OAuth token expired or revoked. The CLI's raw
                        # message ("Failed to authenticate. API Error:
                        # 401 Invalid authentication credentials") tells
                        # the user nothing actionable — replace it with
                        # a recovery instruction.
                        error_msg = (
                            "Claude Code OAuth token expired. "
                            "Run `claude /login` on the host to refresh — "
                            "the container will pick up the new token "
                            "automatically (no restart needed)."
                        )
                    else:
                        error_msg = (
                            evt.get("result")
                            or (errs[0] if errs else None)
                            or "Claude Code error"
                        )

            # 'user' (tool_result) events are internal — ignore.

        rc = proc.wait(timeout=TIMEOUT_SECONDS)
        if rc != 0 and not error_msg:
            stderr_thread.join(timeout=2)
            stderr = "".join(stderr_chunks).strip()
            error_msg = stderr or f"Claude Code exited with code {rc}"
            logger.error(f"Claude Code stream failed (rc={rc}): {error_msg}")

    except subprocess.TimeoutExpired:
        logger.error("Claude Code stream wait() timed out")
        error_msg = error_msg or "Claude Code timed out"
    except GeneratorExit:
        # Client disconnected — terminate the subprocess so we don't
        # leak a Claude Code instance and its API tokens. Re-raise so
        # the caller's StreamingResponse cleanly unwinds.
        logger.info("Claude Code stream cancelled by client")
        raise
    except Exception as e:
        logger.error(f"Claude Code stream error: {e}", exc_info=True)
        error_msg = error_msg or str(e)
    finally:
        watchdog.cancel()
        if timed_out.is_set() and not error_msg:
            error_msg = f"Claude Code timed out after {TIMEOUT_SECONDS}s"
        if proc.poll() is None:
            try:
                proc.terminate()
                proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                proc.kill()
            except Exception:
                pass

    yield StreamDone(
        model=use_model, provider="claude_code",
        tool_calls_count=tool_calls_count,
        claude_session_id=claude_sid,
        error=error_msg,
    )
