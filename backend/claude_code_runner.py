"""
Claude Code subprocess wrapper for AI assistant.

Calls `claude -p` in headless mode. Returns the raw model answer (including
any SAUTIUM_BLOCKS marker) — the chat router parses + hydrates the marker
centrally so this wrapper stays format-agnostic.

Two flavours:
- `call_claude_code` — synchronous, `--output-format json`, returns the
  full answer in one go. Its `tools` profile says what the call may use:
  the library (the assistant's MCP servers), research (the web pair) or
  text (nothing).
- `call_claude_code_stream` — streaming, `--output-format stream-json
  --include-partial-messages`, yields text deltas / tool starts / a
  final done event so the chat router can pipe them into SSE. Always the
  library profile.
"""

import contextlib
import functools
import json
import logging
import os
import re
import shutil
import subprocess
import sys
import threading
from pathlib import Path
from typing import Any, Dict, Iterator, Optional

import psycopg2

if sys.platform not in ("win32", "darwin"):
    import pwd

import claude_code
from providers.base import StreamDone, StreamEvent, TextDelta, ToolStart

logger = logging.getLogger(__name__)

if sys.platform in ("win32", "darwin"):
    # Desktop mode (Win/Mac): mcp config sits next to this module and is
    # regenerated by the launcher with current ports + credentials.
    MCP_CONFIG_PATH = str(Path(__file__).parent / "mcp-windows.json")
else:
    # Docker: written by the backend itself at every start, into the node's
    # own folder (write_docker_mcp_config)
    MCP_CONFIG_PATH = "/app/data/mcp-docker.json"

DEFAULT_MODEL = "sonnet"
ALLOWED_MODELS = {"sonnet", "haiku"}
# Kept below the ~180s at which the browser/LAN drops the streaming connection,
# so the graceful timeout `done` event reaches the client (a clean "took too
# long" message) instead of the stream dying as a raw "network error".
TIMEOUT_SECONDS = 150
# The node's user in Docker (node_user.NODE_USER): the backend and every
# CLI agent (claude, codex) run as it. Its home holds both credential dirs
# (~/.claude, ~/.codex).
AGENT_USER = "agent"

# What a call may use, named on every spawn. Chat text, tool results and the
# catalogue's own names reach the model, so nothing may come from the CLI's
# defaults or from the user's own configuration:
#   --tools decides which built-in tools EXIST ("" = none). A deny-list of
#     names could not follow the CLI's tool set — a PowerShell tool on Windows
#     without Git Bash, Monitor, a REPL.
#   --strict-mcp-config with an explicit --mcp-config decides which MCP
#     servers load — never the user's own servers or the account's connectors.
#   --allowedTools under --permission-mode dontAsk lets exactly the profile's
#     tools run and refuses anything else without a prompt.
# No spawn bypasses permissions: --allowedTools IS the permission system,
# which --dangerously-skip-permissions switches off (measured 2026-07-27).
# Measured 2026-11-02 against a fake of the API on loopback: a request offers
# exactly the profile's tools, a tool of an unlisted server is refused, and
# the user's own defaultMode and allow rules change neither.
LIBRARY = "library"    # the assistant's turns: its MCP servers, no built-in tool
RESEARCH = "research"  # gear research: the web pair, no MCP server
TEXT = "text"          # titles and AI canon: text in, text out, one turn
_NO_MCP = json.dumps({"mcpServers": {}})
# The assistant's MCP servers by name — the keys of its MCP configuration;
# assistant_prompt.py teaches the model their tools by these names.
LIBRARY_SERVERS = ("postgres", "assistant")
# The CLI reads any file a prompt names after an "@" into the request,
# wherever the prompt's text came from (measured 2026-11-02 on 2.1.241 and
# 2.1.316, argv and stdin alike), and sends the system prompt as written. A
# call built from data — a title's exchange, the canon's entries, a gear
# model's name — therefore carries it in the system prompt, and its -p is
# this line. A chat turn's -p is what the owner typed.
_ONE_SHOT_TURN = "Answer as the system prompt asks."

# A CLI that records the system prompt (on by default since 2.1.312) resends
# the first request's copy on every resume, whatever a later launch passes —
# measured through this runner on 2.1.316: a resumed turn given prompt B sent
# prompt A. A chat would keep its first turn's player context and catalogue
# text for good, so recording is off wherever the CLI has the switch. Its
# --help says so: 2.1.278 already lists it ("no effect where recording is not
# yet enabled"), 2.1.241 refuses it as an unknown option.
_SNAPSHOT_SWITCH = "--system-prompt-snapshot"

# assistant turns are SQL + list-building; unbounded interleaved thinking burned
# ~75% of output tokens on a measured chat turn (4.9k-token final turn =
# 57s of UI silence, 2026-07-22). 1024 keeps short planning steps.
_MAX_THINKING_TOKENS = "1024"

# The CLI's auth failures arrive in several shapes — "API Error: 401
# Invalid authentication credentials" carries api_error_status=401, but
# "Failed to authenticate: OAuth session expired and could not be
# refreshed" does NOT (observed on a fresh launcher install with stale
# host credentials, 2026-08-09), and with no credentials at all 2.1.295
# answers "Not logged in · Please run /login" (measured 2026-10-09) — so the
# mapping must also match text. Only consulted inside is_error paths, where
# an authentication mention IS the failure. Every refusal is reported to
# claude_code, which owns the verdict the rest of the backend reads.
OAUTH_EXPIRED_MSG = (
    "Claude Code is signed out — its sign-in expired or was revoked. Sign "
    "in again under More → AI assistant; the assistant and gear research "
    "pick it up from there."
)

_AUTH_FAILURE_RE = re.compile(
    r"oauth|authenticat|not logged in|run /login|invalid api key", re.IGNORECASE)


def _oauth_error(text: Optional[str]) -> bool:
    return bool(_AUTH_FAILURE_RE.search(text or ""))


def _error_text(evt: dict) -> str:
    """The words of a failed result event: `result` on API errors, the
    `errors` list on the CLI's early exits (e.g. `--resume <unknown-id>`),
    else the error subtype itself — `error_max_turns` carries no text."""
    errs = evt.get("errors") or []
    subtype = evt.get("subtype") or ""
    return (evt.get("result") or (errs[0] if errs else "")
            or (subtype if subtype.startswith("error") else ""))


def _auth_failure(evt: dict) -> Optional[str]:
    """The CLI's own words when a result event says authentication failed,
    else None."""
    if not evt.get("is_error"):
        return None
    raw = _error_text(evt)
    if evt.get("api_error_status") == 401 or _oauth_error(raw):
        return raw or "authentication failed"
    return None


def _claude_env() -> dict:
    """Env for the Claude Code subprocess.

    No ANTHROPIC_API_KEY reaches it — the process that starts it dropped the
    node's credentials from its environment (serving.hold_secrets) — so the
    CLI uses OAuth credentials (Claude subscription) rather than the
    pay-as-you-go API account, which it silently bills when the variable is
    set.

    ENABLE_TOOL_SEARCH=false inlines every MCP tool schema upfront
    instead of deferring them behind a ToolSearch call — with deferral
    the model spent a whole API round-trip per conversation turn just
    fetching the postgres tool schema (measured: 3 turns → 2 on the
    same task). The schemas land in the prompt cache, so the extra
    input tokens are cheap.
    """
    env = os.environ.copy()
    env["MAX_THINKING_TOKENS"] = _MAX_THINKING_TOKENS
    env["ENABLE_TOOL_SEARCH"] = "false"
    return env


def _resolve_claude_executable() -> Optional[str]:
    """Path to the native Claude Code binary, bypassing npm's shim.

    The .cmd shim that npm creates on Windows runs through cmd.exe, which
    caps the command line at 8191 chars — far less than our system_prompt
    (~13.5k). Calling the native binary directly uses CreateProcessW with
    the 32k Win32 limit, which fits comfortably. The native binary is
    named `claude.exe` on every platform (the postinstall script copies
    a platform-matched ELF/Mach-O/PE over the placeholder).

    Resolution order: bundled per-user prefix (wizard install) → npm shim
    in PATH redirected to its sibling .exe → raw shim as last resort."""
    bin_rel = (
        Path("node_modules") / "@anthropic-ai" / "claude-code"
        / "bin" / "claude.exe"
    )

    if sys.platform == "win32":
        appdata = os.environ.get("LOCALAPPDATA")
        if appdata:
            bundled = Path(appdata) / "Sautium" / "claude-prefix" / bin_rel
            if bundled.is_file():
                return str(bundled)
    elif sys.platform == "darwin":
        bundled = (
            Path.home() / "Library" / "Application Support"
            / "Sautium" / "claude-prefix" / bin_rel
        )
        if bundled.is_file():
            return str(bundled)

    shim = shutil.which("claude")
    if shim:
        shim_dir = Path(shim).parent
        # npm layout 1 (local prefix): shim in node_modules/.bin/, exe in
        # node_modules/<scope>/<pkg>/bin/ — two dirs up from shim.
        # npm layout 2 (global, Windows): shim in <prefix>/, exe in
        # <prefix>/node_modules/<scope>/<pkg>/bin/ — one dir up.
        for cand in (
            shim_dir.parent / "@anthropic-ai" / "claude-code" / "bin" / "claude.exe",
            shim_dir / "node_modules" / "@anthropic-ai" / "claude-code" / "bin" / "claude.exe",
        ):
            if cand.is_file():
                return str(cand)
        return shim
    return None


def library_mcp_config() -> dict:
    """The assistant's MCP servers as both agent CLIs load them: the file the
    launcher writes on a desktop node, the backend's own on Docker
    (write_docker_mcp_config). Codex turns it into `-c` overrides."""
    return json.loads(Path(MCP_CONFIG_PATH).read_text(encoding="utf-8"))


def _tool_flags(tools: str) -> list[str]:
    """The flags that name what a call of profile `tools` may use (above)."""
    if tools == LIBRARY:
        # The file by its path: the credentials stay off the command line,
        # which other local accounts can read on macOS.
        flags = ["--tools", "", "--mcp-config", MCP_CONFIG_PATH,
                 "--allowedTools", ",".join(f"mcp__{name}" for name in LIBRARY_SERVERS)]
    elif tools == RESEARCH:
        flags = ["--tools", "WebSearch,WebFetch", "--mcp-config", _NO_MCP,
                 "--allowedTools", "WebSearch,WebFetch"]
    elif tools == TEXT:
        flags = ["--tools", "", "--mcp-config", _NO_MCP, "--max-turns", "1"]
    else:
        raise ValueError(f"unknown tool profile {tools!r}")
    return flags + ["--strict-mcp-config", "--permission-mode", "dontAsk"]


def agent_workdir(name: str) -> Path:
    """A Sautium-owned, otherwise empty working directory for an agent CLI.
    The CLI shows the model its working directory and reads project files
    from it and its parents (Claude Code loads every CLAUDE.md up the tree —
    measured), so it is never the backend's own directory, which on the
    launcher is the checkout."""
    if sys.platform == "win32":
        base = Path(os.environ.get("LOCALAPPDATA", Path.home() / "AppData" / "Local"))
        wd = base / "Sautium" / name
    elif sys.platform == "darwin":
        wd = Path.home() / "Library" / "Application Support" / "Sautium" / name
    else:
        wd = Path(pwd.getpwnam(AGENT_USER).pw_dir) / name
    wd.mkdir(parents=True, exist_ok=True)
    return wd


_turns_lock = threading.Lock()
_live_turns = 0


@contextlib.contextmanager
def library_turn():
    """One agent turn that runs the assistant's MCP servers, whose SQL logs
    in as the assistant's role (desktop/db_init.ASSISTANT_ROLE). The role's
    session defaults — read-only, 30 s per statement — are a session's own
    to change, and a statement left running holds its locks after the CLI is
    gone; so when the last live turn ends, every session of the role still
    open is ended. The ending runs under the lock that counts the turns: no
    turn starts its servers while it runs."""
    global _live_turns
    with _turns_lock:
        _live_turns += 1
    try:
        yield
    finally:
        with _turns_lock:
            _live_turns -= 1
            if _live_turns == 0:
                _end_assistant_sessions()


def _end_assistant_sessions() -> None:
    """End every session of the assistant's role in the node's database but
    the query tool's own connection (tools/execute_query, which the API
    providers' turns share and which bounds its statements itself) —
    desktop/db_init.end_assistant_sessions. After a turn that ended
    normally only its servers' closing sessions are left; a statement still
    running is the case worth a warning."""
    from db_pool import get_conn
    from desktop.db_init import end_assistant_sessions
    from tools.execute_query import connection_pid
    try:
        with get_conn() as conn, conn.cursor() as cur:
            running = end_assistant_sessions(cur, keep=connection_pid())
    except psycopg2.Error as e:
        logger.error(f"could not end the assistant's sessions after its turns: {e}")
        return
    if running:
        logger.warning(f"ended {running} statement(s) of the assistant's role still "
                       "running after its turns")


@functools.lru_cache(maxsize=4)
def _has_snapshot_switch(claude_exe: str, mtime_ns: int) -> bool:
    """Whether the CLI at `claude_exe` lists the switch; keyed by its mtime,
    so a CLI updated in place is asked again. One whose --help fails lists
    nothing: the call itself then says what is wrong with it, through the
    refusals the call's own answer maps."""
    kwargs = _agent_kwargs()
    kwargs.update(capture_output=True, text=True, encoding="utf-8",
                  errors="replace", timeout=30)
    return _SNAPSHOT_SWITCH in subprocess.run([claude_exe, "--help"], **kwargs).stdout


def _prompt_flags(claude_exe: str) -> list[str]:
    """What keeps the system prompt as each launch passes it (above)."""
    if _has_snapshot_switch(claude_exe, os.stat(claude_exe).st_mtime_ns):
        return [_SNAPSHOT_SWITCH, "off"]
    return []


def _agent_kwargs() -> dict:
    """Popen setup of a call: spawn_kwargs, the agent's own working directory,
    and stdin closed — with stdin open the CLI waits 3 s for piped input."""
    kwargs = spawn_kwargs(_claude_env())
    kwargs.update(cwd=str(agent_workdir("claude-agent")), stdin=subprocess.DEVNULL)
    return kwargs


def call_claude_code(
    message: str,
    system_prompt: str,
    session_id: Optional[str] = None,
    resume: bool = False,
    model: Optional[str] = None,
    timeout_seconds: Optional[int] = None,
    tools: str = LIBRARY,
    max_turns: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Call Claude Code CLI in headless mode.

    Args:
        message: User message to send
        system_prompt: System prompt for AI assistant context
        session_id: Previous Claude Code session ID for continuity
        resume: Whether to resume a previous session
        model: Model to use (sonnet or haiku). Defaults to DEFAULT_MODEL.
        timeout_seconds: Wallclock cap override. The 150s default exists
            for the chat SSE path; long-running non-interactive callers
            (gear research worker) pass their own budget.
        tools: What the call may use — LIBRARY, RESEARCH or TEXT (above).

    Returns:
        dict with keys: answer, claude_session_id, model, is_error — True
        when the CLI failed and `answer` is its error, not the model's.
    """
    use_model = model if model in ALLOWED_MODELS else DEFAULT_MODEL
    wallclock = timeout_seconds or TIMEOUT_SECONDS

    claude_exe = _resolve_claude_executable()
    if claude_exe is None:
        logger.error("Claude Code CLI not found")
        return {
            "answer": "Claude Code CLI is not installed. Open Settings to run AI agent setup.",
            "claude_session_id": None,
            "model": use_model,
            "is_error": True,
        }

    if tools == LIBRARY:
        turn = ["-p", message, "--system-prompt", system_prompt]
    else:
        turn = ["-p", _ONE_SHOT_TURN, "--system-prompt", f"{system_prompt}\n\n{message}"]
    cmd = [
        claude_exe,
        *turn,
        *_prompt_flags(claude_exe),
        "--output-format", "json",
        "--model", use_model,
        *_tool_flags(tools),
    ]
    if max_turns:
        cmd.extend(["--max-turns", str(max_turns)])

    if resume and session_id:
        cmd.extend(["--resume", session_id])

    logger.info(f"Claude Code call: message of {len(message)} chars, resume={resume}, "
                f"session={session_id}")

    try:
        kwargs = _agent_kwargs()
        kwargs.update(stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                      encoding="utf-8", errors="replace", timeout=wallclock)
        with library_turn() if tools == LIBRARY else contextlib.nullcontext():
            result = subprocess.run(cmd, **kwargs)

        # A failed call still prints its result object: since CLI 2.1.x it
        # exits 1 with the cause in `result` and nothing on stderr, so the
        # exit code alone read as "unknown error" (2026-10-09).
        try:
            output = json.loads(result.stdout)
        except json.JSONDecodeError:
            output = None
        if not isinstance(output, dict):
            if result.returncode != 0:
                stderr = result.stderr.strip()
                logger.error(f"Claude Code failed (rc={result.returncode}): {stderr}")
                return {
                    "answer": f"Claude Code error: {stderr or 'unknown error'}",
                    "claude_session_id": None,
                    "model": use_model,
                    "is_error": True,
                }
            logger.error(f"Failed to parse Claude Code JSON; stdout: {result.stdout[:500]}")
            return {
                "answer": result.stdout.strip() or "Failed to parse Claude Code response",
                "claude_session_id": None,
                "model": use_model,
                "is_error": True,
            }

        raw_answer = output.get("result", "")
        claude_sid = output.get("session_id")
        failed = bool(output.get("is_error")) or result.returncode != 0

        refused = _auth_failure(output)
        if refused:
            claude_code.auth.refused(refused)
            logger.error(f"Claude Code refused the call (rc={result.returncode}): {refused}")
            raw_answer = OAUTH_EXPIRED_MSG
        elif result.returncode != 0:
            cause = _error_text(output) or "unknown error"
            logger.error(f"Claude Code failed (rc={result.returncode}): {cause}")
            raw_answer = f"Claude Code error: {cause}"
        elif not failed:
            claude_code.auth.authenticated()

        logger.info(
            f"Claude Code response: {len(raw_answer)} chars, session={claude_sid}"
        )

        return {
            "answer": raw_answer,
            "claude_session_id": claude_sid,
            "model": use_model,
            "is_error": failed,
        }

    except subprocess.TimeoutExpired:
        logger.error(f"Claude Code timed out after {wallclock}s")
        return {
            "answer": "Request timed out. Please try a simpler query.",
            "claude_session_id": None,
            "model": use_model,
            "is_error": True,
        }
    except FileNotFoundError:
        logger.error("Claude Code CLI not found. Is it installed?")
        return {
            "answer": "Claude Code CLI is not installed in this environment.",
            "claude_session_id": None,
            "model": use_model,
            "is_error": True,
        }
    except Exception as e:
        logger.error(f"Unexpected error calling Claude Code: {e}")
        return {
            "answer": f"Error: {e}",
            "claude_session_id": None,
            "model": use_model,
            "is_error": True,
        }


# Where releases before 2026-11 wrote the Docker node's MCP config: the code's
# folder, the host's ./backend
STALE_MCP_CONFIG = Path(__file__).resolve().parent / "mcp-docker.json"


def write_docker_mcp_config() -> None:
    """The Docker node's MCP config, from its own settings and the servers
    the tree carries (desktop.config_manager.mcp_servers, the launcher's
    builder too). Both servers log in as the assistant's role (desktop/
    db_init.ASSISTANT_ROLE), which reads the catalogue and nothing else.
    Run at every start: the file is the node's, rewritten whole, and
    readable by the user the agents run as — handed to it when the backend
    still runs as root."""
    from config import settings
    from desktop.config_manager import mcp_servers, write_mcp_config
    from desktop.db_init import ASSISTANT_ROLE, assistant_password
    backend_dir = Path(__file__).resolve().parent
    servers = mcp_servers(
        sys.executable, backend_dir / "mcp", backend_dir,
        db={"host": settings.postgres_host, "port": settings.postgres_port,
            "user": ASSISTANT_ROLE,
            "password": assistant_password(settings.postgres_password),
            "name": settings.postgres_db},
        backend_url=os.environ.get("BACKEND_URL", "http://localhost:8000"),
        identity_dir=Path(settings.p2p_identity_dir),
        hqplayer_host=settings.hqplayer_host, hqplayer_port=settings.hqplayer_port,
    )
    path = Path(MCP_CONFIG_PATH)
    write_mcp_config(servers, path)
    if os.geteuid() == 0:
        pw = pwd.getpwnam(AGENT_USER)
        os.chown(path, pw.pw_uid, pw.pw_gid)
    logger.info("MCP config written to %s", path)
    if STALE_MCP_CONFIG.exists():
        try:
            STALE_MCP_CONFIG.unlink()
        except OSError as e:
            logger.warning("%s holds the database password from an earlier release and "
                           "could not be removed here (%s): delete it on the host",
                           STALE_MCP_CONFIG, e)


def spawn_kwargs(env: dict) -> dict:
    """Popen setup shared by every agent CLI spawn — Claude's and Codex's
    chat turns, their one-shots, the sign-ins and status looks — from a
    process that has dropped the node's credentials from its environment
    (serving.hold_secrets; the agent reaches the database through its MCP
    servers' own config and the backend through the API secret file): never
    root — a backend that still runs as root (a Docker image from before the
    node's own user) starts the child as the node's user, with no group but
    its own, and that user's HOME, where the CLIs keep their sign-ins and
    sessions; no flashing console window on Windows."""
    kwargs: dict[str, Any] = {"env": env}
    if sys.platform == "win32":
        kwargs["creationflags"] = subprocess.CREATE_NO_WINDOW
    elif sys.platform != "darwin" and os.geteuid() == 0:
        pw = pwd.getpwnam(AGENT_USER)
        kwargs.update(user=pw.pw_uid, group=pw.pw_gid, extra_groups=[])
        env["HOME"] = pw.pw_dir
    return kwargs


def _spawn_claude(cmd: list[str], stdout=subprocess.PIPE, stderr=subprocess.PIPE):
    """A chat turn's subprocess. Returns the Popen handle."""
    kwargs = _agent_kwargs()
    kwargs.update(stdout=stdout, stderr=stderr, text=True,
                  encoding="utf-8", errors="replace")
    return subprocess.Popen(cmd, **kwargs)


def call_claude_code_stream(
    message: str,
    system_prompt: str,
    session_id: Optional[str] = None,
    resume: bool = False,
    model: Optional[str] = None,
) -> Iterator[StreamEvent]:
    """`_claude_code_stream` as one library turn (library_turn)."""
    with library_turn():
        yield from _claude_code_stream(message, system_prompt, session_id, resume, model)


def _claude_code_stream(
    message: str,
    system_prompt: str,
    session_id: Optional[str],
    resume: bool,
    model: Optional[str],
) -> Iterator[StreamEvent]:
    """Stream variant of `call_claude_code`. Spawns `claude
    --output-format stream-json --include-partial-messages` and turns
    its NDJSON output into provider stream events.

    The partial-messages flag delivers token-level Anthropic stream
    events (`content_block_delta` / `text_delta`) inside a
    `stream_event` wrapper; we forward those as `TextDelta`s. Tool
    invocations show up as either `content_block_start` (tool_use)
    inside `stream_event`, or as fully-formed `assistant` messages
    when the SDK couldn't stream the tool partial — both paths emit
    a single `ToolStart` per call.
    """
    use_model = model if model in ALLOWED_MODELS else DEFAULT_MODEL

    claude_exe = _resolve_claude_executable()
    if claude_exe is None:
        logger.error("Claude Code CLI not found")
        yield StreamDone(
            model=use_model, provider="claude_code",
            error="Claude Code CLI is not installed. Open Settings to run AI agent setup.",
        )
        return

    cmd = [
        claude_exe,
        "-p", message,
        "--output-format", "stream-json",
        "--include-partial-messages",
        "--verbose",  # required for stream-json
        "--model", use_model,
        "--system-prompt", system_prompt,
        *_prompt_flags(claude_exe),
        *_tool_flags(LIBRARY),
    ]
    if resume and session_id:
        cmd.extend(["--resume", session_id])

    logger.info(
        f"Claude Code stream call: message of {len(message)} chars, resume={resume}, "
        f"session={session_id}"
    )

    try:
        proc = _spawn_claude(cmd)
    except FileNotFoundError:
        logger.error("Claude Code CLI not found")
        yield StreamDone(
            model=use_model, provider="claude_code",
            error="Claude Code CLI is not installed",
        )
        return
    except Exception as e:
        logger.error(f"Failed to spawn Claude Code: {e}")
        yield StreamDone(
            model=use_model, provider="claude_code", error=str(e),
        )
        return

    claude_sid: Optional[str] = None
    tool_calls_count = 0
    seen_tool_ids: set[str] = set()
    error_msg: Optional[str] = None

    # Watchdog: kill the subprocess after TIMEOUT_SECONDS regardless of
    # whether it's currently producing output. `proc.wait(timeout=...)`
    # only catches a wedged exit; a subprocess that loops over tool
    # calls forever would otherwise sit on `for line in proc.stdout:`
    # indefinitely.
    timed_out = threading.Event()

    def _watchdog():
        if proc.poll() is None:
            timed_out.set()
            logger.warning(
                f"Claude Code wallclock timeout ({TIMEOUT_SECONDS}s); killing subprocess"
            )
            try:
                proc.kill()
            except Exception:
                pass

    watchdog = threading.Timer(TIMEOUT_SECONDS, _watchdog)
    watchdog.daemon = True
    watchdog.start()

    # Drain stderr in a background thread so it doesn't block on a
    # full pipe and so the message is available on failures.
    stderr_chunks: list[str] = []

    def _drain_stderr():
        if proc.stderr is None:
            return
        try:
            for line in proc.stderr:
                stderr_chunks.append(line)
        except Exception:
            pass

    stderr_thread = threading.Thread(target=_drain_stderr, daemon=True)
    stderr_thread.start()

    def _yield_block_event(block: dict) -> Iterator[StreamEvent]:
        """Translate a single content block (text or tool_use) into
        events. Used when we receive whole assistant messages without
        partial deltas, so we don't drop content."""
        nonlocal tool_calls_count
        bt = block.get("type")
        if bt == "text":
            text = block.get("text", "")
            if text:
                yield TextDelta(text=text)
        elif bt == "tool_use":
            tu_id = block.get("id") or ""
            if tu_id and tu_id in seen_tool_ids:
                return
            if tu_id:
                seen_tool_ids.add(tu_id)
            tool_calls_count += 1
            yield ToolStart(name=block.get("name", "tool"))

    try:
        assert proc.stdout is not None
        for line in proc.stdout:
            line = line.strip()
            if not line:
                continue
            try:
                evt = json.loads(line)
            except json.JSONDecodeError:
                logger.debug(f"Claude stream: skipping non-JSON line: {line[:120]}")
                continue

            t = evt.get("type")

            if t == "system":
                if evt.get("session_id"):
                    claude_sid = evt["session_id"]
                if evt.get("subtype") == "init":
                    servers = evt.get("mcp_servers") or []
                    status = ", ".join(f"{s.get('name')}={s.get('status')}"
                                       for s in servers) or "none"
                    logger.info(
                        f"Claude Code init: model={evt.get('model')}; "
                        f"mcp: {status}; {len(evt.get('tools') or [])} tools")
                    bad = [s for s in servers if s.get("status") != "connected"]
                    if bad:
                        # A dead tool server produces exactly the hedged,
                        # tool-less answers this chat exists to avoid ("if
                        # the catalog is even supported on your system…") —
                        # the model sees tools described in its prompt that
                        # it cannot call. Abort loudly instead of letting it
                        # improvise around them; no legitimate state has a
                        # configured server down.
                        names = ", ".join(f"{s.get('name')} ({s.get('status')})"
                                          for s in bad)
                        error_msg = (
                            f"AI tool server failed to start: {names}. "
                            "Aborting instead of answering without "
                            "search/playback tools — check the backend log "
                            "for the MCP spawn error (launcher: does "
                            "mcp-windows.json point at the venv python and "
                            "mcp/assistant_server.py?)."
                        )
                        logger.error(error_msg)
                        proc.terminate()
                        break

            elif t == "stream_event":
                inner = evt.get("event") or {}
                inner_type = inner.get("type")
                if inner_type == "content_block_delta":
                    delta = inner.get("delta") or {}
                    if delta.get("type") == "text_delta":
                        text = delta.get("text", "")
                        if text:
                            yield TextDelta(text=text)
                elif inner_type == "content_block_start":
                    cb = inner.get("content_block") or {}
                    if cb.get("type") == "tool_use":
                        tu_id = cb.get("id") or ""
                        if tu_id and tu_id not in seen_tool_ids:
                            seen_tool_ids.add(tu_id)
                            tool_calls_count += 1
                            yield ToolStart(name=cb.get("name", "tool"))

            elif t == "assistant":
                # Whole assistant message — only mine it for content
                # we haven't already streamed via stream_event. Tool
                # blocks get deduped by `seen_tool_ids`; text blocks
                # are tricky because partial deltas already covered
                # them. Skip text here to avoid double-rendering.
                msg = evt.get("message") or {}
                for block in msg.get("content", []) or []:
                    if block.get("type") == "tool_use":
                        yield from _yield_block_event(block)

            elif t == "result":
                if evt.get("session_id"):
                    claude_sid = evt["session_id"]
                refused = _auth_failure(evt)
                if refused:
                    # The CLI's raw message tells the user nothing
                    # actionable — replace with a recovery instruction.
                    claude_code.auth.refused(refused)
                    error_msg = OAUTH_EXPIRED_MSG
                elif evt.get("is_error"):
                    # Surface the real error message instead of the
                    # generic "Claude Code error".
                    error_msg = _error_text(evt) or "Claude Code error"
                else:
                    claude_code.auth.authenticated()

            # 'user' (tool_result) events are internal — ignore.

        rc = proc.wait(timeout=TIMEOUT_SECONDS)
        if rc != 0 and not error_msg:
            stderr_thread.join(timeout=2)
            stderr = "".join(stderr_chunks).strip()
            if _oauth_error(stderr):
                claude_code.auth.refused(stderr)
                error_msg = OAUTH_EXPIRED_MSG
            else:
                error_msg = stderr or f"Claude Code exited with code {rc}"
            logger.error(f"Claude Code stream failed (rc={rc}): {error_msg}")

    except subprocess.TimeoutExpired:
        logger.error("Claude Code stream wait() timed out")
        error_msg = error_msg or "Claude Code timed out"
    except GeneratorExit:
        # The consumer abandoned this generator. In the chat path that
        # never happens on client disconnect — the producer thread
        # (routers/chat.py) keeps iterating so the answer still gets
        # persisted; this fires only when the generator itself is
        # discarded (GC / caller crash). Kill the subprocess so we
        # don't leak a Claude Code instance, then unwind.
        logger.info("Claude Code stream generator dropped; killing subprocess")
        raise
    except Exception as e:
        logger.error(f"Claude Code stream error: {e}", exc_info=True)
        error_msg = error_msg or str(e)
    finally:
        watchdog.cancel()
        if timed_out.is_set() and not error_msg:
            error_msg = f"Claude Code timed out after {TIMEOUT_SECONDS}s"
        if proc.poll() is None:
            try:
                proc.terminate()
                proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                proc.kill()
            except Exception:
                pass

    yield StreamDone(
        model=use_model, provider="claude_code",
        tool_calls_count=tool_calls_count,
        agent_session_id=claude_sid,
        error=error_msg,
    )
